package com.project.analyzer.telemetry.lmu.impl.mapper

import com.project.analyzer.telemetry.lmu.api.model.LmuVehicleTelemetry
import com.project.analyzer.telemetry.lmu.impl.shm.structure.Rf2VehicleTelemetry
import com.project.analyzer.utils.shm.toCString

internal fun Rf2VehicleTelemetry.toModel(): LmuVehicleTelemetry = LmuVehicleTelemetry(
    id = id,
    deltaTime = deltaTime,
    elapsedTime = elapsedTime,
    lapNumber = lapNumber,
    lapStartEt = lapStartEt,
    vehicleName = vehicleName.toCString(),
    trackName = trackName.toCString(),
    pos = pos.toVec3(),
    localVel = localVel.toVec3(),
    localAccel = localAccel.toVec3(),
    ori = ori.toOriList(),
    localRot = localRot.toVec3(),
    localRotAccel = localRotAccel.toVec3(),
    gear = gear,
    engineRpm = engineRpm,
    engineWaterTemp = engineWaterTemp,
    engineOilTemp = engineOilTemp,
    clutchRpm = clutchRpm,
    unfilteredThrottle = unfilteredThrottle,
    unfilteredBrake = unfilteredBrake,
    unfilteredSteering = unfilteredSteering,
    unfilteredClutch = unfilteredClutch,
    filteredThrottle = filteredThrottle,
    filteredBrake = filteredBrake,
    filteredSteering = filteredSteering,
    filteredClutch = filteredClutch,
    steeringShaftTorque = steeringShaftTorque,
    front3rdDeflection = front3rdDeflection,
    rear3rdDeflection = rear3rdDeflection,
    frontWingHeight = frontWingHeight,
    frontRideHeight = frontRideHeight,
    rearRideHeight = rearRideHeight,
    drag = drag,
    frontDownforce = frontDownforce,
    rearDownforce = rearDownforce,
    fuel = fuel,
    engineMaxRpm = engineMaxRpm,
    scheduledStops = scheduledStops.toUnsignedInt(),
    overheating = overheating.toBoolean(),
    detached = detached.toBoolean(),
    headlights = headlights.toBoolean(),
    dentSeverity = dentSeverity.copyOf(),
    lastImpactEt = lastImpactEt,
    lastImpactMagnitude = lastImpactMagnitude,
    lastImpactPos = lastImpactPos.toVec3(),
    engineTorque = engineTorque,
    currentSector = currentSector,
    speedLimiter = speedLimiter.toUnsignedInt(),
    maxGears = maxGears.toUnsignedInt(),
    frontTireCompoundIndex = frontTireCompoundIndex.toUnsignedInt(),
    rearTireCompoundIndex = rearTireCompoundIndex.toUnsignedInt(),
    fuelCapacity = fuelCapacity,
    frontFlapActivated = frontFlapActivated.toUnsignedInt(),
    rearFlapActivated = rearFlapActivated.toUnsignedInt(),
    rearFlapLegalStatus = rearFlapLegalStatus.toUnsignedInt(),
    ignitionStarter = ignitionStarter.toUnsignedInt(),
    frontTireCompoundName = frontTireCompoundName.toCString(),
    rearTireCompoundName = rearTireCompoundName.toCString(),
    speedLimiterAvailable = speedLimiterAvailable.toUnsignedInt(),
    antiStallActivated = antiStallActivated.toUnsignedInt(),
    unused = unused.copyOf(),
    rearBrakeBias = rearBrakeBias,
    turboBoostPressure = turboBoostPressure,
    physicsToGraphicsOffset = physicsToGraphicsOffset.copyOf(),
    physicalSteeringWheelRange = physicalSteeringWheelRange,
    batteryChargeFraction = batteryChargeFraction,
    electricBoostMotorTorque = electricBoostMotorTorque,
    electricBoostMotorRpm = electricBoostMotorRpm,
    electricBoostMotorTemperature = electricBoostMotorTemperature,
    electricBoostWaterTemperature = electricBoostWaterTemperature,
    electricBoostMotorState = electricBoostMotorState.toUnsignedInt(),
    expansion = expansion.copyOf(),
    wheels = wheels.map { it.toModel() },
)
